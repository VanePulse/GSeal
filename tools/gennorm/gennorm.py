#!/usr/bin/env python3
"""Generate internal/norm/tables.go and testdata/norm/vectors.txt.

Development-time tool only: building and running GSeal never needs Python.
Uses nothing but the Python 3 standard library (unicodedata); the Unicode
version is the one unicodedata ships and is recorded in both outputs.

    python3 tools/gennorm/gennorm.py && gofmt -w internal/norm/tables.go

Data derived here (UAX #15):
  - canonical combining class (ccc) of every code point with ccc != 0
  - full canonical decomposition of every code point that has one
    (Hangul syllables are decomposed algorithmically and are not listed)
  - primary composites: pairs (a, b) -> c where c's canonical mapping is
    exactly <a b> and c is not excluded from composition. Exclusion is not
    copied from CompositionExclusions.txt: a code point c with a canonical
    decomposition is excluded exactly when NFC(NFD(c)) != c.
"""
import os
import random
import sys
import unicodedata as ud

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
VERSION = ud.unidata_version
MAXCP = 0x10FFFF
SBASE, SCOUNT = 0xAC00, 11172


def is_assigned(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    return ud.category(chr(cp)) != 'Cn'


def canon_mapping(cp):
    d = ud.decomposition(chr(cp))
    if not d or d.startswith('<'):
        return None
    return [int(x, 16) for x in d.split()]


def full_decomp(cp):
    m = canon_mapping(cp)
    if m is None:
        return [cp]
    out = []
    for x in m:
        out.extend(full_decomp(x))
    return out


def hexs(seq):
    return ' '.join('%04X' % c for c in seq)


def main():
    ccc = {}
    decomp = {}
    comp = {}
    for cp in range(MAXCP + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        ch = chr(cp)
        c = ud.combining(ch)
        if c:
            ccc[cp] = c
        if SBASE <= cp < SBASE + SCOUNT:
            continue
        m = canon_mapping(cp)
        if m is None:
            continue
        full = full_decomp(cp)
        assert ud.normalize('NFD', ch) == ''.join(map(chr, full)), hex(cp)
        decomp[cp] = full
        excluded = ud.normalize('NFC', ud.normalize('NFD', ch)) != ch
        if not excluded:
            assert len(m) == 2, hex(cp)
            comp[(m[0], m[1])] = cp

    write_tables(ccc, decomp, comp)
    write_vectors(ccc, comp)


def write_tables(ccc, decomp, comp):
    path = os.path.join(ROOT, 'internal', 'norm', 'tables.go')
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write('// Code generated by tools/gennorm/gennorm.py; DO NOT EDIT.\n\n')
        f.write('package norm\n\n')
        f.write('// UnicodeVersion is the Unicode version the tables were generated from.\n')
        f.write('const UnicodeVersion = "%s"\n\n' % VERSION)
        f.write('// cccTable: canonical combining class of every code point with ccc != 0.\n')
        f.write('var cccTable = map[rune]uint8{\n')
        for cp in sorted(ccc):
            f.write('\t0x%04X: %d,\n' % (cp, ccc[cp]))
        f.write('}\n\n')
        f.write('// decompTable: full canonical decomposition (Hangul syllables excluded).\n')
        f.write('var decompTable = map[rune][]rune{\n')
        for cp in sorted(decomp):
            f.write('\t0x%04X: {%s},\n' % (cp, ', '.join('0x%04X' % x for x in decomp[cp])))
        f.write('}\n\n')
        f.write('// compTable: primary composites, key = first<<21 | second.\n')
        f.write('var compTable = map[uint64]rune{\n')
        for (a, b) in sorted(comp):
            f.write('\t0x%04X<<21 | 0x%04X: 0x%04X,\n' % (a, b, comp[(a, b)]))
        f.write('}\n')


def write_vectors(ccc, comp):
    path = os.path.join(ROOT, 'testdata', 'norm', 'vectors.txt')
    os.makedirs(os.path.dirname(path), exist_ok=True)
    rnd = random.Random(20261124)
    with open(path, 'w', encoding='ascii', newline='\n') as f:
        f.write('# NFC test vectors, Unicode %s, generated by tools/gennorm/gennorm.py\n' % VERSION)
        f.write('# I a b      every assigned code point in [a, b] normalizes to itself\n')
        f.write('# S cp;nfc   single assigned code point whose NFC differs from itself\n')
        f.write('# P src;nfc  canonical composition pair\n')
        f.write('# X src;nfc  base + combining marks in random order (fixed seed)\n')
        assigned = [cp for cp in range(MAXCP + 1) if is_assigned(cp)]
        run = None
        for cp in assigned:
            n = ud.normalize('NFC', chr(cp))
            if n == chr(cp):
                if run and run[1] == cp - 1:
                    run[1] = cp
                else:
                    if run:
                        f.write('I %04X %04X\n' % tuple(run))
                    run = [cp, cp]
                continue
            if run:
                f.write('I %04X %04X\n' % tuple(run))
                run = None
            f.write('S %04X;%s\n' % (cp, hexs(map(ord, n))))
        if run:
            f.write('I %04X %04X\n' % tuple(run))
        for (a, b) in sorted(comp):
            s = chr(a) + chr(b)
            f.write('P %s;%s\n' % (hexs([a, b]), hexs(map(ord, ud.normalize('NFC', s)))))
        marks = sorted(cp for cp in ccc if is_assigned(cp))
        # Starters that take part in composition, plus Hangul jamo / syllables.
        firsts = sorted({a for (a, _) in comp})
        seconds0 = sorted({b for (_, b) in comp if b not in ccc})
        hangul = [0x1100, 0x1112, 0x1161, 0x1175, 0x11A8, 0x11C2, 0xAC00, 0xAC01, 0xD7A3]
        bases = firsts + hangul + [0x41, 0x61, 0x3B1, 0x430, 0x928]
        for _ in range(10000):
            seq = [rnd.choice(bases)]
            for _ in range(rnd.randint(1, 5)):
                r = rnd.random()
                if r < 0.6:
                    seq.append(rnd.choice(marks))
                elif r < 0.8:
                    seq.append(rnd.choice(seconds0 + [0x1161, 0x11A8]))
                else:
                    seq.append(rnd.choice(firsts))
            tail = seq[1:]
            rnd.shuffle(tail)
            seq = seq[:1] + tail
            s = ''.join(map(chr, seq))
            f.write('X %s;%s\n' % (hexs(seq), hexs(map(ord, ud.normalize('NFC', s)))))
    print('wrote', path, file=sys.stderr)


if __name__ == '__main__':
    main()
